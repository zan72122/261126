# -*- coding: utf-8 -*-
"""Procedural photo-like PBR textures (tileable) for 261126-55.
Usage: python3 -I tools/maketex.py <outdir>
Every map is generated by spectral synthesis (FFT -> periodic = seamless)."""
import sys, os, numpy as np
from PIL import Image, ImageFilter

OUT = sys.argv[1]
os.makedirs(OUT, exist_ok=True)
rng = np.random.default_rng(55)

def fbm(h, w, beta=2.0, lo=1.0, hi=None, seed=None):
    r = np.random.default_rng(seed) if seed is not None else rng
    n = r.standard_normal((h, w))
    F = np.fft.fft2(n)
    fy = np.fft.fftfreq(h)[:, None] * h
    fx = np.fft.fftfreq(w)[None, :] * w
    f = np.sqrt(fx * fx + fy * fy)
    f[0, 0] = 1
    amp = 1.0 / f ** (beta / 2)
    amp[f < lo] = 0
    if hi: amp[f > hi] *= np.exp(-(f[f > hi] - hi) / (hi * 0.5))
    out = np.real(np.fft.ifft2(F * amp))
    out -= out.mean(); out /= (out.std() + 1e-9)
    return out

def aniso(h, w, sx, sy, beta=2.0, seed=None):
    r = np.random.default_rng(seed) if seed is not None else rng
    n = r.standard_normal((h, w))
    F = np.fft.fft2(n)
    fy = np.fft.fftfreq(h)[:, None] * h * sy
    fx = np.fft.fftfreq(w)[None, :] * w * sx
    f = np.sqrt(fx * fx + fy * fy); f[0, 0] = 1
    out = np.real(np.fft.ifft2(F / f ** (beta / 2)))
    out -= out.mean(); out /= out.std() + 1e-9
    return out

def norm01(a):
    a = a - a.min(); return a / (a.max() + 1e-9)

def blur(a, r):
    if r <= 0: return a
    h, w = a.shape
    fy = np.fft.fftfreq(h)[:, None]; fx = np.fft.fftfreq(w)[None, :]
    g = np.exp(-2 * (np.pi * r) ** 2 * (fx * fx + fy * fy))
    return np.real(np.fft.ifft2(np.fft.fft2(a) * g))

def voronoi(h, w, n, seed=0):
    r = np.random.default_rng(seed)
    pts = r.random((n, 2)) * [h, w]
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float32)
    d1 = np.full((h, w), 1e9, np.float32); d2 = np.full((h, w), 1e9, np.float32)
    idx = np.zeros((h, w), np.int32)
    for i, (py, px) in enumerate(pts):
        dy = np.abs(yy - py); dy = np.minimum(dy, h - dy)
        dx = np.abs(xx - px); dx = np.minimum(dx, w - dx)
        d = np.sqrt(dx * dx + dy * dy)
        m = d < d1
        d2 = np.where(m, d1, np.minimum(d2, d))
        idx = np.where(m, i, idx)
        d1 = np.where(m, d, d1)
    return d1, d2, idx

def stones(N, count, rmin, rmax, seed, warp=6.0):
    """separated rounded pebbles: returns dome height (0..1), mask, cell index"""
    r = np.random.default_rng(seed)
    d1, d2, idx = voronoi(N, N, count, seed=seed)
    wn = fbm(N, N, 2.0, seed=seed + 1) * warp
    R = (r.random(count) * (rmax - rmin) + rmin)[idx]
    d = d1 + wn * 0.35 + fbm(N, N, 1.2, seed=seed + 2) * 0.6
    m = np.clip((R - d) / 1.6, 0, 1)
    dome = np.sqrt(np.clip(1 - (np.maximum(d, 0) / R) ** 2, 0, 1)) * m
    return dome, m, idx

def normal_from_height(hm, strength):
    gx = (np.roll(hm, -1, 1) - np.roll(hm, 1, 1)) * 0.5 * strength
    gy = (np.roll(hm, -1, 0) - np.roll(hm, 1, 0)) * 0.5 * strength
    nz = np.ones_like(hm)
    l = np.sqrt(gx * gx + gy * gy + 1)
    # OpenGL convention (green up): image row 0 = top -> v=1
    n = np.stack([-gx / l, gy / l, nz / l], -1)
    return ((n * 0.5 + 0.5) * 255).clip(0, 255).astype(np.uint8)

def ao_from_height(hm, r=6):
    b = blur(hm, r)
    return np.clip(1 - np.maximum(b - hm, 0) * 2.2, 0, 1)

def save_rgb(a, name, q=88):
    Image.fromarray((np.clip(a, 0, 1) * 255).astype(np.uint8)).save(os.path.join(OUT, name), quality=q, subsampling=0 if q > 90 else 2)

def save_u8(a, name, q=90):
    Image.fromarray(a).save(os.path.join(OUT, name), quality=q)

def srgb(c):
    return np.array(c, np.float32)[None, None, :]

# ---------------------------------------------------------------- wood (form boards, rough sawn spruce, concrete stained)
def wood():
    H, W = 256, 1024
    yy = np.mgrid[0:H, 0:W][0].astype(np.float32)
    warp = aniso(H, W, 0.15, 1.0, 2.6, seed=1) * 9 + aniso(H, W, 0.05, 1.0, 3.0, seed=2) * 20
    rings = np.sin((yy + warp) * 0.16) * 0.5 + 0.5
    rings = rings ** 4.0 + 0.4 * (np.sin((yy + warp*1.3) * 0.43) * 0.5 + 0.5) ** 6
    fine = aniso(H, W, 0.02, 1.0, 1.6, seed=3)
    saw = np.sin(np.mgrid[0:H, 0:W][1] * 0.21 + aniso(H, W, 1, 0.2, 2, seed=4) * 2) * 0.5 + 0.5  # rough-sawn cross marks
    knots_d, _, _ = voronoi(H, W, 3, seed=5)
    knot = np.exp(-(knots_d / 11) ** 2)
    base = srgb([0.58, 0.46, 0.33])
    late = srgb([0.42, 0.30, 0.19])
    col = base * (1 - rings[..., None] * 0.55) + late * rings[..., None] * 0.55
    col *= (0.92 + 0.08 * fine[..., None])
    col *= (0.96 + 0.06 * saw[..., None])
    col = col * (1 - knot[..., None] * 0.6) + srgb([0.24, 0.15, 0.09]) * knot[..., None] * 0.6
    # weathering grey & concrete splashes
    weather = norm01(fbm(H, W, 2.2, seed=6))
    col = col * (1 - 0.35 * weather[..., None]) + srgb([0.47, 0.46, 0.44]) * 0.35 * weather[..., None]
    sp = fbm(H, W, 1.6, seed=7)
    spl = np.clip((sp - 1.6) * 2.5, 0, 1)
    col = col * (1 - spl[..., None]) + srgb([0.56, 0.56, 0.54]) * spl[..., None]
    h = rings * 0.4 + fine * 0.15 + saw * 0.25 + spl * 0.8 - knot * 0.3
    save_rgb(col, 'wood_c.jpg')
    save_u8(normal_from_height(h, 3.0), 'wood_n.jpg')
    rough = 0.78 + 0.15 * weather - 0.25 * spl * 0 + 0.05 * fine
    orm = np.stack([ao_from_height(h, 4), np.clip(rough, 0, 1), np.zeros_like(h)], -1)
    save_rgb(orm, 'wood_orm.jpg')

# ---------------------------------------------------------------- ground (compacted dirt + gravel, damp)
def ground():
    N = 1024
    r = np.random.default_rng(12)
    dome, m, idx = stones(N, 1500, 7.0, 17.0, 11)
    keep = (r.random(1500) < 0.7)[idx]
    stone = m * keep; dome = dome * keep
    t = r.random(1500)
    tone = (np.stack([t, t, t], -1) * 0.16 + r.random((1500, 3)) * 0.03)
    dirt = fbm(N, N, 2.1, seed=13)
    fine = fbm(N, N, 0.8, seed=14)
    damp = norm01(blur(fbm(N, N, 2.6, seed=15), 6))
    dcol = srgb([0.36, 0.31, 0.25]) * (0.9 + 0.08 * dirt[..., None] + 0.05 * fine[..., None])
    scol = (srgb([0.34, 0.33, 0.31]) + tone[idx] * 0.7 - 0.06) * (0.7 + 0.3 * dome[..., None]) * (0.95 + 0.05 * fine[..., None])
    col = dcol * (1 - stone[..., None]) + scol * stone[..., None]
    col *= (1 - 0.32 * damp[..., None])  # damp = darker
    h = dome * 3.0 + dirt * 0.12 + fine * 0.1
    save_rgb(col, 'ground_c.jpg')
    save_u8(normal_from_height(h, 2.5), 'ground_n.jpg', 85)
    rough = 0.92 - 0.45 * damp ** 2 - 0.1 * stone
    orm = np.stack([ao_from_height(h, 5), np.clip(rough, 0.3, 1), np.zeros_like(h)], -1)
    save_rgb(orm, 'ground_orm.jpg')

# ---------------------------------------------------------------- concrete detail (sand + aggregate + pores) – used by wet & dry slab
def concrete():
    N = 512
    r = np.random.default_rng(22)
    dome, m, idx = stones(N, 700, 4.0, 10.0, 21, 3.0)
    agg = dome * (r.random(700) < 0.75)[idx]
    sand = fbm(N, N, 0.4, seed=23)
    mott = fbm(N, N, 2.4, seed=24)
    pores = np.clip((-fbm(N, N, 0.2, seed=25) - 2.3) * 2, 0, 1)
    # R: aggregate height, G: sand grain, B: mottling, A: pores
    rgba = np.stack([agg, norm01(sand), norm01(mott), pores], -1)
    Image.fromarray((rgba * 255).astype(np.uint8), 'RGBA').save(os.path.join(OUT, 'concrete_d.png'), optimize=True)

# ---------------------------------------------------------------- painted metal (truck) – grime + scratches + concrete dust
def metal():
    N = 512
    grime = norm01(fbm(N, N, 2.2, seed=31))
    drip = norm01(aniso(N, N, 1.0, 0.08, 2.0, seed=32))  # vertical streaks
    scr = np.zeros((N, N), np.float32)
    r = np.random.default_rng(33)
    for _ in range(140):
        x0, y0 = r.random(2) * N; a = r.random() * np.pi; L = r.random() * 60 + 8
        t = np.linspace(0, 1, int(L * 2))
        xs = ((x0 + np.cos(a) * L * t) % N).astype(int); ys = ((y0 + np.sin(a) * L * t) % N).astype(int)
        scr[ys, xs] = 1
    scr = np.clip(blur(scr, 0.6) * 3, 0, 1)
    splat = np.clip((fbm(N, N, 1.7, seed=34) - 1.4) * 2, 0, 1)
    # R: grime, G: streaks, B: scratches, A: concrete splatter
    rgba = np.stack([grime, drip, scr, splat], -1)
    Image.fromarray((rgba * 255).astype(np.uint8), 'RGBA').save(os.path.join(OUT, 'metal_d.png'), optimize=True)
    h = scr * -0.6 + splat * 1.0 + grime * 0.1
    save_u8(normal_from_height(h, 3.0), 'metal_n.jpg')

# ---------------------------------------------------------------- fabric weave (twill) + knit, tileable normal + AO in alpha
def fabric():
    N = 256
    yy, xx = np.mgrid[0:N, 0:N].astype(np.float32)
    p = 2 * np.pi / 8
    warp = np.sin(xx * p) * 0.5 + 0.5
    weft = np.sin(yy * p) * 0.5 + 0.5
    tw = np.sin((xx + yy) * p * 0.5) * 0.5 + 0.5
    h = np.maximum(warp * (tw > 0.5), weft * (tw <= 0.5)) + fbm(N, N, 1.0, seed=41) * 0.12
    h += fbm(N, N, 1.8, seed=42) * 0.15
    n = normal_from_height(h, 1.6)
    a = (ao_from_height(h, 1.5) * 255).astype(np.uint8)[..., None]
    Image.fromarray(np.concatenate([n, a], -1), 'RGBA').save(os.path.join(OUT, 'fabric_n.png'), optimize=True)

# ---------------------------------------------------------------- skin micro detail (pores + fine wrinkles)
def skin():
    N = 256
    pores = -np.clip((fbm(N, N, 0.0, seed=51, hi=60) - 1.0), 0, 3) * 0.5
    h = pores + fbm(N, N, 1.5, seed=52) * 0.25
    save_u8(normal_from_height(h, 0.9), 'skin_n.jpg', 92)

# ---------------------------------------------------------------- hair strands (anisotropic stripes), alpha = strand density
def hair():
    H, W = 256, 128
    s = aniso(H, W, 1.0, 0.03, 1.4, seed=61)
    s2 = aniso(H, W, 1.0, 0.06, 2.0, seed=62)
    v = norm01(s * 0.7 + s2 * 0.5)
    n = normal_from_height(v, 2.5)
    Image.fromarray(np.concatenate([n, (v * 255).astype(np.uint8)[..., None]], -1), 'RGBA').save(os.path.join(OUT, 'hair_n.png'), optimize=True)

# ---------------------------------------------------------------- dog short fur (direction streaks)
def fur():
    N = 256
    s = aniso(N, N, 1.0, 0.12, 1.2, seed=71)
    v = norm01(s)
    save_u8(normal_from_height(v, 2.0), 'fur_n.jpg', 90)


def detail():
    """RGBA height pack for triplanar bump: R twill, G skin pores, B knit/rubber, A fur/hair streak"""
    N = 256
    yy, xx = np.mgrid[0:N, 0:N].astype(np.float32)
    p = 2 * np.pi / 8
    tw = np.sin((xx + yy) * p * 0.5) * 0.5 + 0.5
    warp = np.sin(xx * p) * 0.5 + 0.5; weft = np.sin(yy * p) * 0.5 + 0.5
    twill = np.maximum(warp * (tw > 0.5), weft * (tw <= 0.5)) + fbm(N, N, 1.0, seed=81) * 0.15 + fbm(N, N, 2.2, seed=82) * 0.12
    pores = -np.clip(fbm(N, N, 0.0, seed=83, hi=50) - 1.2, 0, 3) * 0.6 + fbm(N, N, 1.4, seed=84) * 0.3
    knit = (np.sin(xx * 2 * np.pi / 6) * 0.5 + 0.5) * (np.sin(yy * 2 * np.pi / 10 + np.sin(xx * 2 * np.pi / 12) * 1.5) * 0.5 + 0.5) + fbm(N, N, 1.0, seed=85) * 0.2
    furs = aniso(N, N, 1.0, 0.08, 1.3, seed=86)
    rgba = np.stack([norm01(twill), norm01(pores), norm01(knit), norm01(furs)], -1)
    Image.fromarray((rgba * 255).astype(np.uint8), 'RGBA').save(os.path.join(OUT, 'detail_h.png'), optimize=True)

wood(); ground(); concrete(); metal(); detail()
print('ok')
